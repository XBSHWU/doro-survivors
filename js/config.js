export function loadSaveData() {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      return {
        coins: parsed.coins || 0,
        bestTime: parsed.bestTime || 0,
        bestKills: parsed.bestKills || 0,
        lang: parsed.lang || 'zh',
        upgrades: {
          might: 0,
          maxHp: 0,
          speed: 0,
          xpGain: 0,
          revive: 0,
          ...(parsed.upgrades || {}),
        },
      };
    }
  } catch (_) {}
  return {
    coins: 0,
    bestTime: 0,
    bestKills: 0,
    lang: 'zh',
    upgrades: { might: 0, maxHp: 0, speed: 0, xpGain: 0, revive: 0 },
  };
}

export function writeSaveData(data) {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(data));
  } catch (_) {}
}
