export function loadSaveData() {
  const defaults = {
    coins: 0,
    bestTime: 0,
    bestKills: 0,
    lang: 'zh',
    customAvatar: null,
    upgrades: { might: 0, maxHp: 0, speed: 0, xpGain: 0, rerolls: 0, revive: 0 },
    claimedAchievements: [],
    stats: {
      totalKills: 0,
      totalBursts: 0,
      totalEvolutions: 0,
      maxCoinsRun: 0,
      bossesDefeated: [],
      mapsPlayed: [],
    },
  };
  try {
    // Migrate from v1 save if present
    const raw = localStorage.getItem(STORAGE_KEY) || localStorage.getItem('doro_survivors_save_v1');
    if (raw) {
      const p = JSON.parse(raw);
      return {
        ...defaults,
        ...p,
        upgrades: { ...defaults.upgrades, ...(p.upgrades || {}) },
        stats: {
          ...defaults.stats,
          ...(p.stats || {}),
          bossesDefeated: Array.isArray(p.stats?.bossesDefeated) ? p.stats.bossesDefeated : [],
          mapsPlayed: Array.isArray(p.stats?.mapsPlayed) ? p.stats.mapsPlayed : [],
        },
        claimedAchievements: Array.isArray(p.claimedAchievements) ? p.claimedAchievements : [],
      };
    }
  } catch (_) {}
  return defaults;
}

export function writeSaveData(data) {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(data));
  } catch (_) {}
}
